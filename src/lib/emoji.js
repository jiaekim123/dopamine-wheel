/**
 * FNV-1a 32-bit 해시.
 * 같은 입력 → 같은 출력. 충돌은 랜덤 분포.
 */
export function fnv1a(str) {
  let hash = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    hash ^= str.charCodeAt(i);
    // 32-bit FNV-1a prime
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

/**
 * 이름을 받아 EMOJI_POOL의 한 이모지를 안정적으로 반환.
 * 같은 이름은 항상 같은 이모지를 받는다.
 */
export function nameToEmoji(name) {
  return EMOJI_POOL[fnv1a(name) % EMOJI_POOL.length];
}
